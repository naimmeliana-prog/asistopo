export function filterCatalog(query: string): BOEConvocatoriaItem[] {
  if (!query || !query.trim()) return REAL_CONVOCATORIAS_CATALOG;

  const normalize = (str: string) => {
    return (str || "")
      .toLowerCase()
      .normalize("NFD")
      .replace(/[\u0300-\u036f]/g, "")
      .replace(/[^a-z0-9\s]/g, "");
  };

  const normalizedQuery = normalize(query);
  const queryWords = normalizedQuery.split(/\s+/).filter(w => w.length > 0);
  const stopWords = ["de", "la", "el", "en", "y", "o", "a", "un", "una", "del", "al", "para", "con", "por"];
  const significantWords = queryWords.filter(w => !stopWords.includes(w) || queryWords.length === 1);
  const wordsToSearch = significantWords.length > 0 ? significantWords : queryWords;

  const getStems = (word: string): string[] => {
    const stems = [word];
    if (word.length > 4) {
      if (word.endsWith("es")) {
        stems.push(word.slice(0, -2));
      } else if (word.endsWith("s")) {
        stems.push(word.slice(0, -1));
      } else if (word.endsWith("cion") || word.endsWith("cion")) {
        stems.push(word);
        stems.push(word.slice(0, -4) + "ciones");
        stems.push(word.slice(0, -4));
      }
    }
    return stems;
  };

  return REAL_CONVOCATORIAS_CATALOG.filter(item => {
    const titleNorm = normalize(item.title);
    const descNorm = normalize(item.description);
    return wordsToSearch.some(word => {
      const stems = getStems(word);
      return stems.some(stem => titleNorm.includes(stem) || descNorm.includes(stem));
    });
  });
}
